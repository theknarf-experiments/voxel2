//! The layer manager: registration, recursive on-demand generation with
//! cross-thread deduplication, and the chunk cache.

use std::any::{Any, TypeId};
use std::cell::RefCell;
use std::collections::HashMap;

use ahash::AHashSet as HashSet;
use std::marker::PhantomData;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::{Arc, OnceLock, RwLock};

use glam::IVec3;
use voxel_core::seed::{chunk_seed, Rng};

use crate::layer::{chunk_bounds, chunk_range, layer_key, Dep, IAabb, Layer, LayerKey};

/// (layer instance, internal level, chunk coordinate).
type CacheKey = (LayerKey, u32, IVec3);
type ErasedChunk = Arc<dyn Any + Send + Sync>;

const CACHE_SHARDS: usize = 32;

fn shard_of(key: &CacheKey) -> usize {
    // The coordinate carries the entropy; the layer key is already a hash.
    let (layer, level, coord) = key;
    let mixed = layer
        ^ (*level as u64).wrapping_mul(0x9E37_79B9)
        ^ (coord.x as u32 as u64).wrapping_mul(0x85EB_CA6B)
        ^ (coord.y as u32 as u64).wrapping_mul(0xC2B2_AE35) << 1
        ^ (coord.z as u32 as u64).wrapping_mul(0x27D4_EB2F) << 2;
    (mixed >> 13) as usize % CACHE_SHARDS
}
type Slot = Arc<OnceLock<ErasedChunk>>;
type GenerateFn = Box<dyn Fn(&LayerManager, IVec3, u32) -> ErasedChunk + Send + Sync>;

struct LayerEntry {
    name: String,
    type_id: TypeId,
    stable_id: u64,
    extent: IVec3,
    levels: u32,
    /// `Layer::level_padding(l)` captured at registration, so ensure-load
    /// can resolve internal-level dependencies without the concrete type.
    level_pads: Vec<IVec3>,
    deps: Vec<Dep>,
    generate: GenerateFn,
}

/// Owns all registered layers and their generated chunks.
///
/// Generation is blocking and recursive: requesting a chunk generates its
/// dependency chunks first (deduplicated across threads — concurrent
/// requests for the same chunk generate it exactly once). Everything is
/// regenerable, so the cache can be dropped at any time.
pub struct LayerManager {
    world_seed: u64,
    layers: HashMap<LayerKey, LayerEntry>,
    /// Sharded so parallel ensure-load workers don't serialize on one
    /// lock: every generated chunk takes the lock once per dependency
    /// read, which at eight threads is hundreds of thousands of
    /// acquisitions (measured: one global mutex made a parallel pass
    /// SLOWER than the serial one).
    cache: [RwLock<HashMap<CacheKey, Slot>>; CACHE_SHARDS],
    /// Chunks generated by a READ rather than by [`LayerManager::ensure_loaded`].
    /// Read-driven generation still works (nothing silently goes missing),
    /// but it is serial, unprioritized, and lands wherever the read
    /// happens — often the main thread. A non-zero count means some
    /// consumer's working set is not covered by an ensure-load pass.
    read_generated: AtomicUsize,
}

/// What an [`LayerManager::ensure_loaded`] pass did.
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct EnsureStats {
    /// Chunks this pass generated (across the whole dependency closure).
    pub generated: usize,
    /// Chunks already present.
    pub present: usize,
}

thread_local! {
    /// Generation stack for cycle detection (a cycle would otherwise
    /// deadlock on the chunk's `OnceLock`).
    static GEN_STACK: RefCell<Vec<(LayerKey, u32, IVec3)>> = const { RefCell::new(Vec::new()) };
    /// Set while this thread generates inside an ensure-load pass, so
    /// read-driven generation can be counted separately.
    static IN_ENSURE: std::cell::Cell<bool> = const { std::cell::Cell::new(false) };
}

impl LayerManager {
    pub fn new(world_seed: u64) -> Self {
        Self {
            world_seed,
            layers: HashMap::new(),
            cache: std::array::from_fn(|_| RwLock::new(HashMap::new())),
            read_generated: AtomicUsize::new(0),
        }
    }

    /// Register the default instance of a layer (instance name =
    /// `L::NAME`). Its dependencies must already be registered, which
    /// makes the layer graph a DAG by construction.
    pub fn register<L: Layer>(&mut self, layer: L) {
        self.register_as(L::NAME, layer);
    }

    /// Register a NAMED instance: data-driven stacks register several
    /// differently-parameterized instances of one layer type, each with
    /// its own cache and seed stream.
    pub fn register_as<L: Layer>(&mut self, instance: &str, layer: L) {
        let key = layer_key(instance);
        let deps = layer.dependencies();
        for dep in &deps {
            assert!(
                self.layers.contains_key(&dep.key),
                "layer {instance:?} depends on an unregistered layer; register dependencies first",
            );
        }
        assert!(
            !self.layers.contains_key(&key),
            "layer instance {instance:?} registered twice",
        );

        let extent = layer.chunk_extent();
        assert!(
            extent.cmpge(IVec3::ZERO).all(),
            "chunk_extent must be non-negative"
        );
        let levels = layer.levels();
        assert!(levels >= 1, "a layer needs at least one level");
        let level_pads: Vec<IVec3> = (0..levels).map(|l| layer.level_padding(l)).collect();
        let arc = Arc::new(layer);
        let gen_arc = arc.clone();
        let generate: GenerateFn = Box::new(move |mgr, coord, level| {
            let ctx = LayerCtx::<L> {
                mgr,
                key,
                coord,
                level,
                layer: gen_arc.clone(),
                _layer: PhantomData,
            };
            Arc::new(gen_arc.generate(&ctx, coord))
        });
        self.layers.insert(
            key,
            LayerEntry {
                name: instance.to_string(),
                type_id: TypeId::of::<L>(),
                stable_id: key,
                extent,
                levels,
                level_pads,
                deps,
                generate,
            },
        );
    }

    /// All chunks of `L` covering `bounds` (world meters), generating any
    /// that don't exist yet. This is the top-level entry point streaming
    /// code uses.
    pub fn get<L: Layer>(&self, bounds: IAabb) -> LayerView<L> {
        self.get_named::<L>(L::NAME, bounds)
    }

    /// Final-level chunks of a NAMED instance covering `bounds`.
    pub fn get_named<L: Layer>(&self, instance: &str, bounds: IAabb) -> LayerView<L> {
        let key = layer_key(instance);
        let final_level = self.entry(key).levels - 1;
        self.get_named_at_level::<L>(instance, bounds, final_level)
    }

    /// Chunks of `L` at a specific internal level covering `bounds`.
    pub fn get_at_level<L: Layer>(&self, bounds: IAabb, level: u32) -> LayerView<L> {
        self.get_named_at_level::<L>(L::NAME, bounds, level)
    }

    pub fn get_named_at_level<L: Layer>(
        &self,
        instance: &str,
        bounds: IAabb,
        level: u32,
    ) -> LayerView<L> {
        let key = layer_key(instance);
        let entry = self.entry(key);
        assert_eq!(
            entry.type_id,
            TypeId::of::<L>(),
            "layer instance {instance:?} is not a {:?}",
            std::any::type_name::<L>()
        );
        let (lo, hi) = chunk_range(entry.extent, bounds);
        let mut chunks = Vec::new();
        for z in lo.z..=hi.z {
            for y in lo.y..=hi.y {
                for x in lo.x..=hi.x {
                    let coord = IVec3::new(x, y, z);
                    let erased = self.get_chunk_erased(key, coord, level);
                    chunks.push((
                        coord,
                        erased.downcast::<L::Chunk>().expect("layer chunk type mismatch"),
                    ));
                }
            }
        }
        LayerView { chunks }
    }

    /// A single final-level chunk of `L`'s default instance.
    pub fn get_chunk<L: Layer>(&self, coord: IVec3) -> Arc<L::Chunk> {
        let key = layer_key(L::NAME);
        let final_level = self.entry(key).levels - 1;
        self.get_chunk_at::<L>(coord, final_level)
    }

    /// A single chunk of `L`'s default instance at a specific level.
    pub fn get_chunk_at<L: Layer>(&self, coord: IVec3, level: u32) -> Arc<L::Chunk> {
        let erased = self.get_chunk_erased(layer_key(L::NAME), coord, level);
        erased
            .downcast::<L::Chunk>()
            .expect("layer chunk type mismatch")
    }

    fn get_chunk_erased(&self, layer: LayerKey, coord: IVec3, level: u32) -> ErasedChunk {
        let key = (layer, level, coord);
        let shard = &self.cache[shard_of(&key)];
        // Hits are the overwhelming majority once a region is ensured.
        let existing = shard.read().unwrap().get(&key).cloned();
        let slot: Slot = match existing {
            Some(slot) => slot,
            None => shard.write().unwrap().entry(key).or_default().clone(),
        };
        if let Some(chunk) = slot.get() {
            return chunk.clone();
        }
        if !IN_ENSURE.with(|f| f.get()) {
            // Diagnostic only (racy by nature): this read is about to
            // generate work an ensure-load pass should have covered.
            let n = self.read_generated.fetch_add(1, Ordering::Relaxed);
            let cap: usize = std::env::var("VOXEL_LOG_LAYERS")
                .ok()
                .map_or(0, |v| v.parse().unwrap_or(40));
            if n < cap {
                eprintln!(
                    "read-generated {:?} level {level} at {coord}",
                    self.layers[&layer].name
                );
            }
            if n == 0 && cap > 0 {
                eprintln!(
                    "first read-driven generation, backtrace:\n{}",
                    std::backtrace::Backtrace::force_capture()
                );
            }
        }

        GEN_STACK.with(|stack| {
            assert!(
                !stack.borrow().contains(&key),
                "layer dependency cycle detected at {:?} {coord}",
                self.layers[&layer].name
            );
            stack.borrow_mut().push(key);
        });
        let result = slot
            .get_or_init(|| (self.layers[&layer].generate)(self, coord, level))
            .clone();
        GEN_STACK.with(|stack| {
            stack.borrow_mut().pop();
        });
        result
    }

    /// **The** generation entry point (LayerProcGen's `EnsureLoadedInBounds`):
    /// generate every chunk of `instance` covering `bounds`, resolving the
    /// declared dependency closure FIRST, nearest-first, in parallel.
    ///
    /// Reads stay correct without this — they generate on demand — but a
    /// read-driven closure is serial, unprioritized, and runs on whatever
    /// thread reads (often the main one). Consumers should ensure-load the
    /// region they are about to query, then read; [`Self::read_generated`]
    /// reports whether that discipline holds.
    pub fn ensure_loaded(&self, instance: &str, bounds: IAabb) -> EnsureStats {
        let focus = IVec3::new(
            bounds.min.x.saturating_add(bounds.max.x) / 2,
            0,
            bounds.min.z.saturating_add(bounds.max.z) / 2,
        );
        self.ensure_loaded_regions(instance, std::slice::from_ref(&bounds), focus)
    }

    /// Ensure `instance` over a SET of regions — one per consumer chunk,
    /// not one hull around them. A LOD field is a shell, not a box: the
    /// bounding hull of everything that queries a layer would generate
    /// planning for the hollow middle too. Chunks generate nearest-first
    /// from `focus`.
    pub fn ensure_loaded_regions(
        &self,
        instance: &str,
        regions: &[IAabb],
        focus: IVec3,
    ) -> EnsureStats {
        let key = layer_key(instance);
        let level = self.entry(key).levels - 1;
        let mut stats = EnsureStats::default();
        self.ensure_key(key, regions, level, focus, &mut stats);
        stats
    }

    fn ensure_key(
        &self,
        key: LayerKey,
        regions: &[IAabb],
        level: u32,
        focus: IVec3,
        stats: &mut EnsureStats,
    ) {
        let entry = self.entry(key);
        // 1. What do these regions actually need from this layer?
        let mut wanted: HashSet<IVec3> = HashSet::default();
        for region in regions {
            let (lo, hi) = chunk_range(entry.extent, *region);
            for z in lo.z..=hi.z {
                for y in lo.y..=hi.y {
                    for x in lo.x..=hi.x {
                        wanted.insert(IVec3::new(x, y, z));
                    }
                }
            }
        }
        let mut missing: Vec<IVec3> = wanted
            .into_iter()
            .filter(|coord| {
                let ck = (key, level, *coord);
                // In flight on another thread counts as missing: joining
                // it is what "ensure" means.
                let present = self.cache[shard_of(&ck)]
                    .read()
                    .unwrap()
                    .get(&ck)
                    .is_some_and(|slot| slot.get().is_some());
                if present {
                    stats.present += 1;
                }
                !present
            })
            .collect();
        if missing.is_empty() {
            return;
        }
        stats.generated += missing.len();

        // 2. Providers for exactly the chunks about to be generated
        //    (chunks already present already have theirs) — the
        //    EnsureChunkProviders order: inputs exist before Create runs.
        let own_bounds: Vec<IAabb> = missing
            .iter()
            .map(|coord| chunk_bounds(entry.extent, *coord))
            .collect();
        if level > 0 {
            let pad = entry.level_pads[level as usize];
            let padded: Vec<IAabb> = own_bounds.iter().map(|b| b.inflate(pad)).collect();
            self.ensure_key(key, &padded, level - 1, focus, stats);
        }
        for dep in &entry.deps {
            let dep_final = self.entry(dep.key).levels - 1;
            let padded: Vec<IAabb> = own_bounds.iter().map(|b| b.inflate(dep.padding)).collect();
            self.ensure_key(dep.key, &padded, dep_final, focus, stats);
        }

        // 3. Generate nearest-first, in parallel once there is enough work
        //    to pay for the threads.
        let extent = entry.extent.max(IVec3::ONE);
        let focus_coord = IVec3::new(
            focus.x.div_euclid(extent.x),
            focus.y.div_euclid(extent.y),
            focus.z.div_euclid(extent.z),
        );
        missing.sort_by_key(|c| {
            let d = (*c - focus_coord).clamp(IVec3::splat(-30_000), IVec3::splat(30_000));
            d.x * d.x + d.y * d.y + d.z * d.z
        });

        const PARALLEL_MIN: usize = 32;
        let threads = std::env::var("VOXEL_ENSURE_THREADS")
            .ok()
            .and_then(|v| v.parse().ok())
            .unwrap_or_else(|| {
                // Leave cores for the render and main threads: this pool
                // runs while the app is drawing, and saturating every core
                // trades frame time for planning throughput.
                std::thread::available_parallelism().map_or(2, |n| (n.get() / 2).clamp(1, 4))
            });
        if threads == 1 || missing.len() < PARALLEL_MIN {
            self.in_ensure(|| {
                for coord in &missing {
                    self.get_chunk_erased(key, *coord, level);
                }
            });
            return;
        }
        let next = AtomicUsize::new(0);
        std::thread::scope(|scope| {
            for _ in 0..threads {
                scope.spawn(|| {
                    self.in_ensure(|| loop {
                        let i = next.fetch_add(1, Ordering::Relaxed);
                        let Some(&coord) = missing.get(i) else {
                            break;
                        };
                        self.get_chunk_erased(key, coord, level);
                    });
                });
            }
        });
    }

    fn in_ensure<R>(&self, f: impl FnOnce() -> R) -> R {
        let prev = IN_ENSURE.with(|f| f.replace(true));
        let out = f();
        IN_ENSURE.with(|f| f.set(prev));
        out
    }

    /// Chunks generated by reads rather than by an ensure-load pass. Zero
    /// means every consumer's working set was pre-generated properly.
    pub fn read_generated(&self) -> usize {
        self.read_generated.load(Ordering::Relaxed)
    }

    pub fn reset_read_generated(&self) {
        self.read_generated.store(0, Ordering::Relaxed);
    }

    /// Number of cached chunks (all layers).
    pub fn cached_chunks(&self) -> usize {
        self.cache
            .iter()
            .map(|shard| shard.read().unwrap().len())
            .sum()
    }

    /// Drop every cached chunk. Safe at any quiescent point — everything is
    /// regenerable.
    pub fn evict_all(&self) {
        for shard in &self.cache {
            shard.write().unwrap().clear();
        }
    }

    /// Rolling eviction: drop cached chunks whose bounds do not intersect
    /// `keep` (world meters). In-flight chunks (still generating) are
    /// retained regardless. Returns the number of chunks dropped —
    /// everything is regenerable, so this is safe at any time.
    pub fn evict_outside(&self, keep: IAabb) -> usize {
        let mut dropped = 0;
        for shard in &self.cache {
            let mut cache = shard.write().unwrap();
            let before = cache.len();
            cache.retain(|(layer, _level, coord), slot| {
                if slot.get().is_none() {
                    return true; // in-flight
                }
                let extent = self.layers[layer].extent;
                chunk_bounds(extent, *coord).intersects(keep)
            });
            dropped += before - cache.len();
        }
        dropped
    }

    fn entry(&self, key: LayerKey) -> &LayerEntry {
        self.layers
            .get(&key)
            .unwrap_or_else(|| panic!("layer instance is not registered"))
    }
}

/// Read access handed to [`Layer::generate`]: the chunk's own identity/seed
/// plus padded views of declared dependency layers.
pub struct LayerCtx<'a, L: Layer> {
    mgr: &'a LayerManager,
    key: LayerKey,
    coord: IVec3,
    level: u32,
    layer: Arc<L>,
    _layer: PhantomData<L>,
}

impl<L: Layer> LayerCtx<'_, L> {
    /// Which internal level is being generated (0-based).
    pub fn level(&self) -> u32 {
        self.level
    }

    /// Read level `level() - 1` chunks of this same layer covering
    /// `bounds` — the internal-levels contextual pattern. Panics at level
    /// 0 or when `bounds` exceeds the declared
    /// [`Layer::level_padding`].
    pub fn get_self(&self, bounds: IAabb) -> LayerView<L> {
        assert!(
            self.level > 0,
            "layer {:?} level 0 has no previous level to read",
            L::NAME
        );
        let allowed = self
            .chunk_bounds()
            .inflate(self.layer.level_padding(self.level));
        assert!(
            allowed.contains(bounds),
            "layer {:?} level {} reads outside its declared level padding: allowed {:?}, requested {:?}",
            L::NAME,
            self.level,
            allowed,
            bounds
        );
        let name = self.mgr.entry(self.key).name.clone();
        self.mgr
            .get_named_at_level::<L>(&name, bounds, self.level - 1)
    }

    /// Deterministic seed for this chunk (instance- and level-distinct).
    pub fn seed(&self) -> u64 {
        let entry = self.mgr.entry(self.key);
        chunk_seed(
            self.mgr.world_seed,
            entry.stable_id ^ (self.level as u64).wrapping_mul(0x9E3779B97F4A7C15),
            self.coord,
        )
    }

    /// Deterministic RNG for this chunk.
    pub fn rng(&self) -> Rng {
        Rng::new(self.seed())
    }

    /// World-space bounds of this chunk.
    pub fn chunk_bounds(&self) -> IAabb {
        chunk_bounds(self.mgr.entry(self.key).extent, self.coord)
    }

    /// Read chunks of dependency layer `D`'s default instance.
    pub fn get<D: Layer>(&self, bounds: IAabb) -> LayerView<D> {
        self.get_named::<D>(D::NAME, bounds)
    }

    /// Read chunks of a NAMED dependency instance covering `bounds`.
    ///
    /// Panics if the instance was not declared in
    /// [`Layer::dependencies`], or if `bounds` exceeds this chunk's
    /// bounds inflated by the declared padding — the LayerProcGen
    /// containment rule that determinism rests on.
    pub fn get_named<D: Layer>(&self, instance: &str, bounds: IAabb) -> LayerView<D> {
        let entry = self.mgr.entry(self.key);
        let dep_key = layer_key(instance);
        let dep = entry
            .deps
            .iter()
            .find(|d| d.key == dep_key)
            .unwrap_or_else(|| {
                panic!(
                    "layer {:?} reads {instance:?} without declaring it as a dependency",
                    entry.name,
                )
            });
        let allowed = self.chunk_bounds().inflate(dep.padding);
        assert!(
            allowed.contains(bounds),
            "layer {:?} reads {instance:?} outside its declared padding: \
             allowed {:?}, requested {:?} — declare Dep::named({instance:?}, {:?})",
            entry.name,
            allowed,
            bounds,
            needed_padding(self.chunk_bounds(), bounds, dep.padding),
        );
        self.mgr.get_named::<D>(instance, bounds)
    }
}

/// Per-axis padding that would cover `requested` from `own`, never
/// shrinking what is already declared — the number to put in the `Dep`.
fn needed_padding(own: IAabb, requested: IAabb, declared: IVec3) -> IVec3 {
    let axis = |own_min: i32, own_max: i32, req_min: i32, req_max: i32, have: i32| {
        own_min
            .saturating_sub(req_min)
            .max(req_max.saturating_sub(own_max))
            .max(have)
    };
    IVec3::new(
        axis(own.min.x, own.max.x, requested.min.x, requested.max.x, declared.x),
        axis(own.min.y, own.max.y, requested.min.y, requested.max.y, declared.y),
        axis(own.min.z, own.max.z, requested.min.z, requested.max.z, declared.z),
    )
}

/// Chunks of one layer covering a requested region, in deterministic
/// (z, y, x ascending) order.
pub struct LayerView<L: Layer> {
    chunks: Vec<(IVec3, Arc<L::Chunk>)>,
}

impl<L: Layer> LayerView<L> {
    pub fn iter(&self) -> impl Iterator<Item = (IVec3, &L::Chunk)> {
        self.chunks.iter().map(|(c, chunk)| (*c, chunk.as_ref()))
    }

    pub fn len(&self) -> usize {
        self.chunks.len()
    }

    pub fn is_empty(&self) -> bool {
        self.chunks.is_empty()
    }
}
